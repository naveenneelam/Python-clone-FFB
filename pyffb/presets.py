"""Built-in, conservative profiles for popular racing titles.

These are starting points, not a substitute for tuning against a specific car,
tyre model and wheelbase.  All profiles deliberately avoid motor, encoder,
current-limit and brake-resistor settings.  Those belong to the firmware's
hardware commissioning tools and can damage hardware or injure the user.

Process names are lower-case executable basenames.  Game updates occasionally
rename executables; users can duplicate a profile and edit ``exe_names`` in the
JSON file, or use the generic profile.
"""

from __future__ import annotations

from dataclasses import replace
from typing import Iterable

from .models import Profile, WheelSettings

DESKTOP_PROFILE_ID = "desktop"
GENERIC_PROFILE_ID = "generic"


def _p(
    profile_id: str,
    name: str,
    game: str,
    exes: Iterable[str],
    description: str,
    notes: Iterable[str],
    **settings: object,
) -> Profile:
    profile = Profile(
        id=profile_id,
        name=name,
        game=game,
        exe_names=tuple(exes),
        description=description,
        notes=tuple(notes),
        settings=WheelSettings(**settings),
        builtin=True,
    ).validated()[0]
    return profile


