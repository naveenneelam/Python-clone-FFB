PROFILES: tuple[Profile, ...] = _PROFILES
PROFILE_BY_ID: dict[str, Profile] = {profile.id: profile for profile in PROFILES}


def builtin_profiles() -> tuple[Profile, ...]:
    return PROFILES


def get_builtin(profile_id: str) -> Profile:
    try:
        return PROFILE_BY_ID[profile_id]
    except KeyError as exc:
        raise KeyError(f"unknown built-in profile: {profile_id}") from exc


def with_custom_settings(profile_id: str, settings: WheelSettings) -> Profile:
    """Return a built-in profile with user settings, keeping its game mapping."""

    return replace(get_builtin(profile_id), settings=settings, builtin=True)
